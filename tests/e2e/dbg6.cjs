const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1360, height: 900 } })
  p.on('pageerror', (e) => console.log('err', e.message)); p.on('console', (m) => m.type() === 'error' && console.log('console', m.text().slice(0, 200)))
  p.on('request', (r) => { const u = r.url(); if (!u.startsWith('http://127.0.0.1')) console.log('EXTERNAL REQUEST', u) })
  const B = 'http://127.0.0.1:5173'
  await p.goto(B)
  await p.getByLabel('Email').fill('ops1@example.com'); await p.getByLabel('Password').fill('password123')
  await p.getByRole('button', { name: 'Sign in', exact: true }).click()
  await p.getByRole('button', { name: 'Sign out' }).waitFor()
  await p.goto(B + '/requests/20000000-0000-0000-0000-000000000003')
  const t = Date.now()
  await p.getByLabel('Upload policy illustrations (pis)').setInputFiles(['/tmp/claude-0/scan2/SCAN_SG_TokioMarine-CIMB_TermProtectPlus_2022.pdf', '/tmp/claude-0/scan2/SCAN_SG_Singlife_EliteTermII_2024.pdf'])
  const cmp = p.getByRole('region', { name: 'PI comparison' })
  await cmp.getByText(/with OCR/).first().waitFor({ timeout: 30000 })
  await p.screenshot({ path: __dirname + '/shots/15-ocr-progress.png' })
  await cmp.getByLabel('Insurer / plan for PI 2').waitFor({ timeout: 600000 })
  console.log('done in', Math.round((Date.now() - t) / 1000), 's')
  const labels = ['Insurer / plan', 'Sum assured (S$)', 'Policy term (years)', 'Premium term (years)', 'Premium (S$, monthly)', 'Total distribution cost (S$)']
  for (const i of [1, 2]) for (const l of labels) console.log(`PI${i} ${l}: ${await cmp.getByLabel(`${l} for PI ${i}`).inputValue()}`)
  console.log((await cmp.innerText()).match(/Could not read[^\n]*|Scanned[^\n]*/g))
  await p.screenshot({ path: __dirname + '/shots/16-ocr-result.png', fullPage: true })
  await b.close()
})()
