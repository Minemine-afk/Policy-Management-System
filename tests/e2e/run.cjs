    const view = await (await fetch('http://127.0.0.1:54321/rest/v1/request_list?select=priority,urgent_auto,due_at,paused_at', { headers: h })).json()
    const table = await fetch('http://127.0.0.1:54321/rest/v1/pi_requests?select=priority', { headers: h })
